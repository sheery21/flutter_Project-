class User{
  final String gender;
  final String name;
  final String email;
  final String phone;
  final String cell;
  final String picture;
  final String city;
  final String state;
  final String country;
  final String dob;
  User({
    required this.gender,
    required this.name,
    required this.email,
    required this.phone,
    required this.cell,
    required this.picture,
    required this.city,
    required this.state,
    required this.country,
    required this.dob,
  });
}

